# The language picked in the menu. language.js saves it in the "googtrans" cookie, like "/en/fr"
# No cookie (or one we don't know) means English
def chosen_language():
    language = request.cookies.get("googtrans", "").split("/")[-1]
    if language in RECEIPT_TEXT:
        return language
    return "en"


# Farsi and Arabic are written right to left
RIGHT_TO_LEFT = ["fa", "ar"]


# The receipt words for the chosen language, plus what the HTML email needs for right to left languages
def receipt_text():
    language = chosen_language()
    rtl = language in RIGHT_TO_LEFT
    text = dict(RECEIPT_TEXT[language])
    text["lang"] = language
    text["dir"] = "rtl" if rtl else "ltr"
    # Which side the amounts line up on. In right to left they go on the left
    text["start"] = "right" if rtl else "left"
    text["end"] = "left" if rtl else "right"
    return text
